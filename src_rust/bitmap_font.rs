/// Рисует строку `text` в ARGB-буфере softbuffer (u32 на пиксель) начиная
/// с левого верхнего угла (x, y). Символы без растра (эмодзи и т.п.)
/// пропускаются без сдвига курсора, поэтому "👆 Взять" отрисуется просто
/// как аккуратно вписанное "Взять".
pub fn draw_text(
    buffer: &mut [u32],
    buf_w: usize,
    buf_h: usize,
    x: i32,
    y: i32,
    text: &str,
    color: u32,
    scale: i32,
) {
    let scale = scale.max(1);
    let mut cursor_x = x;

    for ch in text.chars() {
        if let Some(rows) = glyph(ch) {
            for (row_idx, row_bits) in rows.iter().enumerate() {
                for col in 0..GLYPH_W {
                    let bit = (GLYPH_W - 1 - col) as u32;
                    if (row_bits >> bit) & 1 == 1 {
                        let px0 = cursor_x + col * scale;
                        let py0 = y + (row_idx as i32) * scale;
                        for sy in 0..scale {
                            for sx in 0..scale {
                                let px = px0 + sx;
                                let py = py0 + sy;
                                if px >= 0 && py >= 0 && (px as usize) < buf_w && (py as usize) < buf_h {
                                    buffer[py as usize * buf_w + px as usize] = color;
                                }
                            }
                        }
                    }
                }
            }
            cursor_x += (GLYPH_W + 1) * scale;
        }
    }
}

/// Ширина строки в пикселях при данном масштабе — используется, чтобы
/// вертикально центрировать подпись пункта меню по высоте строки.
pub fn text_width(text: &str, scale: i32) -> i32 {
    let scale = scale.max(1);
    let mut count = 0i32;
    for ch in text.chars() {
        if glyph(ch).is_some() {
            count += 1;
        }
    }
    (count * (GLYPH_W + 1) - 1).max(0) * scale
}
